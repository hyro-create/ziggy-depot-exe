const { JSDOM } = require("jsdom");
const base = process.argv[2];
let fails = 0;
const ok = (n, c, d="") => { console.log((c ? "  OK    " : "  ÉCHEC ") + n + (c ? "" : " — " + d)); if (!c) fails++; };
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const dom = await JSDOM.fromURL(base + "/", { runScripts: "dangerously", pretendToBeVisual: true, beforeParse(w) {
    w.fetch = (u, o) => fetch(new URL(u, base), o);
    w.confirm = () => true; w.prompt = () => "SUPPRIMER"; w.open = () => null;
  }});
  const w = dom.window, d = w.document, $ = id => d.getElementById(id);
  const errors = []; w.addEventListener("error", e => errors.push(e.message));
  await sleep(1200);
  ok("page chargée, aucune erreur JavaScript", errors.length === 0, errors.join(";"));
  ok("bannière « clé manquante » visible", !$("banner").hidden);
  ok("message d'accueil invite à ouvrir les paramètres", /paramètres/i.test($("log").textContent));
  ok("logo présent", !!d.querySelector("img.logo"));
  $("gear").click(); await sleep(800);
  ok("paramètres ouverts via l'engrenage", !$("settings").hidden);
  ok("statut : Clé manquante", $("glabel").textContent === "Clé manquante", $("glabel").textContent);
  ok("5 sections présentes", ["sec-gemini","sec-general","sec-voice","sec-memory","sec-about"].every(i => $(i)));
  ok("autostart désactivé et expliqué hors Windows", $("autostart").disabled === true && /Windows/.test($("autostartHint").textContent));
  $("gkey").value = "AI" + "zaSyFAKE_UI_0123456789_abcdefghijklmnopqrs";
  $("gshow").click(); ok("Afficher/Masquer : champ visible", $("gkey").type === "text"); $("gshow").click(); ok("…puis masqué", $("gkey").type === "password");
  $("gsave").click(); await sleep(1000);
  ok("Enregistrer : message de résultat réel", /enregistrée/.test($("gmsg").textContent), $("gmsg").textContent);
  ok("champ vidé après enregistrement", $("gkey").value === "");
  ok("statut : Clé enregistrée (non testée)", $("glabel").textContent === "Clé enregistrée", $("glabel").textContent);
  ok("dernier caractères affichés, clé jamais renvoyée", /••••/.test($("gsaved").textContent) && !/FAKE_UI/.test(d.body.textContent));
  ok("bannière masquée après enregistrement", $("banner").hidden);
  $("gtest").click(); await sleep(6000);
  ok("Tester : n'affiche PAS « Connecté » avec une fausse clé", $("glabel").textContent !== "Connecté" && /Erreur réseau|Clé invalide/.test($("glabel").textContent), $("glabel").textContent);
  ok("Tester : message explicatif en français", $("gmsg").textContent.length > 20, $("gmsg").textContent);
  $("gmodels").click(); await sleep(4000);
  ok("Actualiser les modèles : erreur expliquée (hors ligne)", $("gmsg").textContent.length > 10 && !$("gmsg").classList.contains("ok"), $("gmsg").textContent);
  $("rate").value = "1.5"; $("rate").dispatchEvent(new w.Event("input")); await sleep(900);
  const st = await (await fetch(base + "/api/settings", { headers: { "X-Ziggy-Token": d.querySelector("meta[name=ziggy-token]").content } })).json();
  ok("débit de voix enregistré côté serveur", st.settings.voice.rate === 1.5, JSON.stringify(st.settings.voice));
  $("tts").checked = true; $("tts").dispatchEvent(new w.Event("change")); await sleep(600);
  ok("synthèse vocale activée et bouton Voix actif", $("spk").classList.contains("on"));
  $("backup").click(); await sleep(700);
  ok("Sauvegarde de la mémoire : résultat réel", /Sauvegarde créée|Aucune mémoire/.test($("mmsg").textContent), $("mmsg").textContent);
  ok("dossier de données affiché", $("dataDir").textContent.length > 3);
  $("showHist").click(); await sleep(500); ok("historique consultable", !$("hist").hidden);
  $("gdel").click(); await sleep(800);
  ok("Supprimer la clé : statut Clé manquante", $("glabel").textContent === "Clé manquante", $("glabel").textContent);
  $("wipe").click(); await sleep(700);
  ok("Supprimer toute la mémoire (avec confirmation tapée)", /Mémoire supprimée|supprimée/.test($("mmsg").textContent), $("mmsg").textContent);
  $("resetPrefs").click(); await sleep(600);
  ok("Réinitialiser les préférences : message réel", /réinitialisées/.test($("smsg").textContent), $("smsg").textContent);
  $("help").click(); ok("Bouton aide présent", true);
  $("sclose").click(); ok("paramètres refermés", $("settings").hidden);
  q = $("q"); q.value = "bonjour"; $("f").requestSubmit(); await sleep(1200);
  ok("chat sans clé : message clair affiché", /Aucune clé Gemini/.test($("log").textContent), $("log").textContent.slice(-200));
  ok("toujours aucune erreur JavaScript", errors.length === 0, errors.join(";"));
  console.log(fails ? `\n✖ ${fails} échec(s)` : "\n✔ Interface : tout est OK");
  process.exit(fails ? 1 : 0);
})().catch(e => { console.error("CRASH", e); process.exit(2); });
